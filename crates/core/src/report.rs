fn html(
    diff: &FileDiff,
    visible: &[bool],
    left_label: &str,
    right_label: &str,
    labels: &ReportLabels,
    now: SystemTime,
) -> String {
    let s = &diff.stats;
    let mut out = String::new();
    out.push_str("<!doctype html>\n<html lang=\"");
    out.push_str(&escape(&labels.lang));
    out.push_str("\"><head><meta charset=\"utf-8\">");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
    out.push_str(&format!(
        "<title>NurDiff – {} ↔ {}</title>",
        escape(left_label),
        escape(right_label)
    ));
    out.push_str(&format!("<style>{STYLE}</style></head><body>\n"));
    out.push_str(&format!("<h1>{}</h1>\n", escape(&labels.title)));
    out.push_str(&format!(
        "<p class=\"meta\">{} ↔ {}</p>\n",
        escape(left_label),
        escape(right_label)
    ));
    if diff.identical {
        out.push_str(&format!(
            "<p class=\"stats\">{}</p>\n",
            escape(&labels.identical)
        ));
    } else {
        let stats = labels
            .stats
            .replace("{changed}", &s.changed.to_string())
            .replace("{leftOnly}", &s.left_only.to_string())
            .replace("{rightOnly}", &s.right_only.to_string())
            .replace("{equal}", &s.equal.to_string());
        out.push_str(&format!("<p class=\"stats\">{}</p>\n", escape(&stats)));
    }
    if diff.approximate {
        out.push_str(&format!(
            "<p class=\"stats\">{}</p>\n",
            escape(&labels.approximate)
        ));
    }
    // The widths are fixed here: the first row may be a full-width "equal rows" row.
    out.push_str(
        "<table>\n<colgroup><col style=\"width:3.5rem\"><col><col style=\"width:3.5rem\"><col></colgroup>\n",
    );
    let mut i = 0;
    while i < diff.rows.len() {
        if !visible[i] {
            let from = i;
            while i < diff.rows.len() && !visible[i] {
                i += 1;
            }
            out.push_str(&format!(
                "<tr class=\"skip\"><td colspan=\"4\">{}</td></tr>\n",
                escape(&labels.skipped.replace("{count}", &(i - from).to_string()))
            ));
            continue;
        }
        let row = &diff.rows[i];
        let (class, lm, rm): (&str, Vec<Mark>, Vec<Mark>) = match (row.kind, &row.left, &row.right)
        {
            (RowKind::Changed, Some(l), Some(r)) => {
                let (lm, rm) = inline_marks(&l.text, &r.text, &diff.options);
                ("chg", lm, rm)
            }
            (RowKind::LeftOnly, ..) => ("del", Vec::new(), Vec::new()),
            (RowKind::RightOnly, ..) => ("add", Vec::new(), Vec::new()),
            _ => ("eq", Vec::new(), Vec::new()),
        };
        let cell = |c: &Option<Cell>, marks: &[Mark], side: &str| match c {
            Some(c) => format!(
                "<td class=\"n\">{}</td><td class=\"c {side}\">{}</td>",
                c.number,
                marked(&c.text, marks)
            ),
            None => format!("<td class=\"n\"></td><td class=\"c {side} none\"></td>"),
        };
        let none = if row.left.is_none() || row.right.is_none() {
            " none"
        } else {
            ""
        };
        out.push_str(&format!(
            "<tr class=\"{class}{none}\">{}{}</tr>\n",
            cell(&row.left, &lm, "l"),
            cell(&row.right, &rm, "r")
        ));
        i += 1;
    }
    out.push_str("</table>\n");
    out.push_str(&format!(
        "<p class=\"foot\">{}</p>\n</body></html>\n",
        escape(&labels.generated.replace("{date}", &format_utc(now)))
    ));
    out
}

/// `2026-10-16 01:20 UTC`.
fn format_utc(t: SystemTime) -> String {
    let secs = t.duration_since(UNIX_EPOCH).map_or(0, |d| d.as_secs()) as i64;
    let (days, rem) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    // Days since 1970 to civil date (algorithm by H. Hinnant).
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!(
        "{year:04}-{month:02}-{day:02} {:02}:{:02} UTC",
        rem / 3600,
        rem % 3600 / 60
    )
}

