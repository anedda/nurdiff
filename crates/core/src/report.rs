//! Report of a file comparison to share: unified diff (text) or standalone HTML
//! page. It is generated here, in the core, so the app and the CLI use it in the same way.

use std::time::{SystemTime, UNIX_EPOCH};

use serde::Deserialize;

use crate::diff::{Cell, Row, RowKind};
use crate::inline::{inline_marks, Mark};
use crate::FileDiff;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ReportFormat {
    /// Standalone HTML page (styles included), with the modified parts highlighted.
    Html,
    /// Unified diff, like `diff -u` / `git diff`.
    Unified,
}

/// The texts of the HTML page, already translated by the caller (the core does not know languages).
/// `stats` and `skipped` are templates with placeholders: `{changed}`, `{leftOnly}`, `{rightOnly}`,
/// `{equal}` and `{count}`; `generated` has `{date}`.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct ReportLabels {
    pub lang: String,
    pub title: String,
    pub identical: String,
    pub stats: String,
    pub skipped: String,
    pub generated: String,
    /// Shown when the comparison is approximate (see [`FileDiff::approximate`]).
    pub approximate: String,
}

impl Default for ReportLabels {
    fn default() -> Self {
        ReportLabels {
            lang: "en".into(),
            title: "File comparison".into(),
            identical: "The files are identical.".into(),
            stats: "{changed} modified · {leftOnly} left only · {rightOnly} right only · {equal} identical".into(),
            skipped: "… {count} identical lines …".into(),
            generated: "Generated by NurDiff on {date}".into(),
            approximate: "Approximate comparison: the result is correct, but it may have more changed lines than the minimum.".into(),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReportOptions {
    /// Equal rows around each difference; `None` = the whole file.
    pub context: Option<usize>,
    pub labels: ReportLabels,
}

impl Default for ReportOptions {
    fn default() -> Self {
        ReportOptions {
            context: Some(3),
            labels: ReportLabels::default(),
        }
    }
}

/// Generates the report. `left_label` and `right_label` are the names shown (usually the paths).
pub fn file_report(
    diff: &FileDiff,
    left_label: &str,
    right_label: &str,
    format: ReportFormat,
    options: &ReportOptions,
) -> String {
    let visible = visible_rows(&diff.rows, options.context);
    match format {
        ReportFormat::Unified => unified(&diff.rows, &visible, left_label, right_label),
        ReportFormat::Html => html(
            diff,
            &visible,
            left_label,
            right_label,
            &options.labels,
            SystemTime::now(),
        ),
    }
}

/// Which rows to show: the differences and `context` rows around each (all of them without `context`).
pub fn visible_rows(rows: &[Row], context: Option<usize>) -> Vec<bool> {
    let Some(ctx) = context else {
        return vec![true; rows.len()];
    };
    let mut visible = vec![false; rows.len()];
    // Each row is filled once: the windows of nearby differences overlap, and with a large context they would
    // cost rows × context.
    let mut filled = 0;
    for (i, row) in rows.iter().enumerate() {
        if row.kind != RowKind::Equal {
            let from = i.saturating_sub(ctx).max(filled);
            let to = i.saturating_add(ctx).min(rows.len() - 1);
            if from <= to {
                visible[from..=to].fill(true);
                filled = to + 1;
            }
        }
    }
    visible
}

// --- Unified diff ---------------------------------------------------------------------

fn unified(rows: &[Row], visible: &[bool], left_label: &str, right_label: &str) -> String {
    if rows.iter().all(|r| r.kind == RowKind::Equal) {
        return String::new();
    }
    let mut out = format!("--- {left_label}\n+++ {right_label}\n");
    let (mut last_left, mut last_right) = (0usize, 0usize);
    let mut i = 0;
    while i < rows.len() {
        if !visible[i] {
            advance(&rows[i], &mut last_left, &mut last_right);
            i += 1;
            continue;
        }
        // A group: consecutive visible rows.
        let mut lines: Vec<(char, &str)> = Vec::new();
        let (mut left_count, mut right_count) = (0usize, 0usize);
        let (mut left_start, mut right_start): (Option<usize>, Option<usize>) = (None, None);
        let (before_left, before_right) = (last_left, last_right);
        while i < rows.len() && visible[i] {
            let row = &rows[i];
            if row.kind == RowKind::Equal {
                // An equal row always has both sides; if one is missing it is skipped, instead of stopping the app.
                let (Some(l), Some(r)) = (row.left.as_ref(), row.right.as_ref()) else {
                    advance(row, &mut last_left, &mut last_right);
                    i += 1;
                    continue;
                };
                left_start.get_or_insert(l.number);
                right_start.get_or_insert(r.number);
                lines.push((' ', &l.text));
                left_count += 1;
                right_count += 1;
                advance(row, &mut last_left, &mut last_right);
                i += 1;
            } else {
                // A series of different rows: first all the removed ones, then all the added ones.
                let (mut dels, mut adds): (Vec<&Cell>, Vec<&Cell>) = (Vec::new(), Vec::new());
                while i < rows.len() && visible[i] && rows[i].kind != RowKind::Equal {
                    dels.extend(rows[i].left.as_ref());
                    adds.extend(rows[i].right.as_ref());
                    advance(&rows[i], &mut last_left, &mut last_right);
                    i += 1;
                }
                if let Some(c) = dels.first() {
                    left_start.get_or_insert(c.number);
                }
                if let Some(c) = adds.first() {
                    right_start.get_or_insert(c.number);
                }
                left_count += dels.len();
                right_count += adds.len();
                lines.extend(dels.iter().map(|c| ('-', c.text.as_str())));
                lines.extend(adds.iter().map(|c| ('+', c.text.as_str())));
            }
        }
        // A side without rows in the group starts at the row that precedes it (0 if none).
        let ls = if left_count == 0 {
            before_left
        } else {
            left_start.unwrap_or(before_left)
        };
        let rs = if right_count == 0 {
            before_right
        } else {
            right_start.unwrap_or(before_right)
        };
        out.push_str(&format!(
            "@@ -{} +{} @@\n",
            range(ls, left_count),
            range(rs, right_count)
        ));
        for (prefix, text) in lines {
            out.push(prefix);
            out.push_str(text);
            out.push('\n');
        }
    }
    out
}

fn advance(row: &Row, last_left: &mut usize, last_right: &mut usize) {
    if let Some(c) = &row.left {
        *last_left = c.number;
    }
    if let Some(c) = &row.right {
        *last_right = c.number;
    }
}

/// `start,count`, with the abbreviated form of `diff -u` when the count is 1.
fn range(start: usize, count: usize) -> String {
    if count == 1 {
        start.to_string()
    } else {
        format!("{start},{count}")
    }
}

// --- HTML ---------------------------------------------------------------------------------

fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(c),
        }
    }
    out
}

/// The text of a row in HTML, with the indicated parts (UTF-16 units) inside `<mark>`.
fn marked(text: &str, marks: &[Mark]) -> String {
    if marks.is_empty() {
        return escape(text);
    }
    let mut out = String::new();
    let mut unit = 0usize;
    let mut open = false;
    for c in text.chars() {
        let inside = marks.iter().any(|m| unit >= m.start && unit < m.end);
        if inside && !open {
            out.push_str("<mark>");
            open = true;
        } else if !inside && open {
            out.push_str("</mark>");
            open = false;
        }
        out.push_str(&escape(&c.to_string()));
        unit += c.len_utf16();
    }
    if open {
        out.push_str("</mark>");
    }
    out
}

