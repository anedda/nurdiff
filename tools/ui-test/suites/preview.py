"""Folder preview: rows, sizes, bar, filters, cancellation, Espandi, keyboard. A suite of the UI test (see README.md in this folder)."""
from harness import *


def run(browser):
    print("== Anteprima: una riga alla volta, confronto sul posto ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    page.evaluate("window.__pick = '/o/uno'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/o/uno'")
    page.evaluate("window.__pick = '/o/due'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_function("document.querySelectorAll('.dir-preview .dir-body .vl-row').length >= 3")
    calls = lambda c: page.evaluate("(c) => window.__calls.filter(x => x.cmd === c).map(x => x.args)", c)
    rowof = lambda name: page.locator(".dir-preview .dir-body .dir-row", has_text=name).first
    sel_n = lambda: page.locator(".dir-preview .dir-row.selected").count()
    mark = lambda name: rowof(name).locator(".dir-mark").inner_text().strip()
    main_btn = page.locator('.tabpage:not([hidden]) .paths button.primary')
    n_tabs = page.locator(".doctab").count()
    check("tre righe: i nomi uguali sono sulla stessa riga, gli altri hanno il lato opposto vuoto",
          page.locator(".dir-preview .dir-body .dir-row").count() == 3
          and rowof("solo-sinistra").locator(".half.empty").count() == 1
          and rowof("solo-destra").locator(".half.empty").count() == 1
          and rowof("a.txt").locator(".half.empty").count() == 0)
    check("il centro è vuoto dove le voci non sono ancora confrontate (niente «↔»)", mark("a.txt") == "" and mark("solo-sinistra") == "" and mark("solo-destra") == "")
    ctitle = lambda name: rowof(name).locator(".dir-mark").get_attribute("title")
    check("il suggerimento del centro distingue riga con coppia e voce singola",
          "doppio clic" in ctitle("a.txt") and "nulla da confrontare" in ctitle("solo-sinistra"))
    check("senza nessun confronto il riepilogo non dice «0 identici» (non si sa), ma dice quanti non sono confrontati",
          page.locator(".dir-preview .dir-pills .stat.identical").count() == 0 and page.locator(".dir-preview .dir-pills .stat.notCompared").count() == 1
          and "identic" not in page.locator(".dir-preview .dir-pills").get_attribute("aria-label"))
    check("e nemmeno «0 diversi»: prima del confronto non si sa, e le coppie non confrontate potrebbero esserlo",
          page.locator(".dir-preview .dir-pills .stat.changed").count() == 0 and "diverse," not in page.locator(".dir-preview .dir-pills").get_attribute("aria-label")
          and page.locator(".dir-preview .dir-pills .stat.leftOnly").count() == 1 and page.locator(".dir-preview .dir-pills .stat.rightOnly").count() == 1)
    check("senza scelta il pulsante è «Confronta»", main_btn.inner_text().strip() == "Confronta")
    rowof("a.txt").locator(".half").first.click()
    check("un clic su un lato sceglie la riga intera (una sola)", sel_n() == 1 and main_btn.inner_text().strip() == "Confronta selezione")
    check("il suggerimento dice quale riga", "«a.txt»" in page.locator(".dir-preview .notice").first.inner_text())
    page.screenshot(path=f"{SHOTS}/preview_selection.png")
    rowof("a.txt").locator(".dir-mark").click()
    check("un secondo clic (anche al centro) toglie la scelta", sel_n() == 0 and main_btn.inner_text().strip() == "Confronta")
    rowof("solo-sinistra").locator(".half").first.click()
    check("riga con un solo lato: scelta, ma il pulsante resta «Confronta»", sel_n() == 1 and main_btn.inner_text().strip() == "Confronta"
          and "non si può confrontare" in page.locator(".dir-preview .notice").first.inner_text())
    page.keyboard.press("Escape")
    check("Esc toglie la scelta", sel_n() == 0)
    # in-place comparison
    rowof("a.txt").locator(".half").nth(1).click()
    page.evaluate("window.__calls.length = 0; window.__recStatus = 'identical'")
    main_btn.click()
    page.wait_for_function("Array.from(document.querySelectorAll('.dir-preview .dir-row')).find(r => r.textContent.includes('a.txt')).querySelector('.dir-mark').textContent.trim() === '='")
    rc = calls("recompare_entry")
    # the channel of the tab (Cancel in another tab does not stop it) is checked apart
    tab_channel = all(c.pop("channel", "").startswith("tab") for c in rc)
    check("«Confronta selezione» confronta solo quella riga, sul posto",
          tab_channel and rc == [{"left": "/o/uno", "right": "/o/due", "rel": "a.txt", "filter": NOFILTER}] and page.locator(".doctab").count() == n_tabs
          and not calls("compare_files") and not calls("compare_directories") and page.locator(".dir-preview").count() == 1, str(rc))
    check("il segno diventa «=»", mark("a.txt") == "=")
    check("prima di qualsiasi confronto non c'era «0 identici»; ora che una voce è identica compare, col suo numero",
          page.locator(".dir-preview .dir-pills .stat.identical").count() == 1 and page.locator(".dir-preview .dir-pills .stat.identical strong").inner_text() == "1")
    check("con una voce identica e le altre non confrontate «diversi» resta nascosto: si sa solo ciò che è stato confrontato",
          page.locator(".dir-preview .dir-pills .stat.changed").count() == 0)
    page.evaluate("window.__recStatus = 'different'")
    rowof("a.txt").click(button="right")
    items = [i.strip() for i in page.locator(".ctx-menu button").all_inner_texts()]
    check("menu contestuale: confronta, apri in un tab e «Mostra nel file manager» per ogni lato",
          items == ["Confronta selezione", "Apri in un nuovo tab", "Mostra nel file manager (sinistra)", "Mostra nel file manager (destra)"], str(items))
    page.locator(".ctx-menu button", has_text="Confronta selezione").click()
    page.wait_for_function("Array.from(document.querySelectorAll('.dir-preview .dir-row')).find(r => r.textContent.includes('a.txt')).querySelector('.dir-mark').textContent.trim() === '\u2260'")
    check("dal menu: la riga diventa «≠»", mark("a.txt") == "\u2260")
    # "Show in file manager" from the entry on both sides: one path per side
    revealed = lambda: page.evaluate("window.__calls.filter(c => c.cmd === 'plugin:opener|reveal_item_in_dir').map(c => c.args.paths)")
    # the opening goes through a dynamic import: we wait for the call to arrive
    wait_reveal = lambda n: page.wait_for_function("(n) => window.__calls.filter(c => c.cmd === 'plugin:opener|reveal_item_in_dir').length === n", arg=n, timeout=5000)
    rowof("a.txt").click(button="right")
    page.locator(".ctx-menu button", has_text="Mostra nel file manager (destra)").click()
    wait_reveal(1)
    rowof("a.txt").click(button="right")
    page.locator(".ctx-menu button", has_text="Mostra nel file manager (sinistra)").click()
    wait_reveal(2)
    check("«Mostra nel file manager» apre il file manager sul percorso del lato scelto",
          revealed() == [["/o/due/a.txt"], ["/o/uno/a.txt"]], str(revealed()))
    rowof("solo-sinistra").click(button="right")
    dis = page.locator(".ctx-menu button").evaluate_all("els => els.map(e => e.disabled)")
    labels = [i.strip() for i in page.locator(".ctx-menu button").all_inner_texts()]
    check("menu su una riga con un lato solo: confronto e tab disattivati, una sola voce «Mostra nel file manager» attiva",
          dis == [True, True, False] and labels[2] == "Mostra nel file manager", f"{dis} {labels}")
    page.locator(".ctx-menu button", has_text="Mostra nel file manager").click()
    wait_reveal(3)
    check("e apre il percorso del solo lato che esiste", revealed()[-1] == ["/o/uno/solo-sinistra.txt"], str(revealed()))
    rowof("solo-sinistra").click(button="right")
    page.wait_for_selector(".ctx-menu")
    page.keyboard.press("Escape")
    page.evaluate("window.__recFail = 'boom'")
    # Esc with the menu open only closes the menu: the choice is made explicitly on a.txt
    check("Esc chiude il menu senza togliere la scelta della riga", page.locator(".ctx-menu").count() == 0)
    if rowof("a.txt").evaluate("e => !e.classList.contains('selected')"):
        rowof("a.txt").locator(".half").first.click()
    main_btn.click()
    page.wait_for_function("Array.from(document.querySelectorAll('.dir-preview .dir-row')).find(r => r.textContent.includes('a.txt')).querySelector('.dir-mark').textContent.trim() === '!'")
    check("confronto fallito: «!» con il motivo", "boom" in (rowof("a.txt").locator(".dir-mark").get_attribute("title") or ""))
    page.evaluate("window.__recFail = null")
    # modified paths: "Compare" is back
    page.fill('input[aria-label="Sinistra"]', "/o/altro")
    check("campi modificati: il pulsante torna «Confronta»", main_btn.inner_text().strip() == "Confronta")
    page.fill('input[aria-label="Sinistra"]', "/o/uno")
    check("campi ripristinati: di nuovo «Confronta selezione»", main_btn.inner_text().strip() == "Confronta selezione")
    # double click on a file: new tab
    page.evaluate("window.__fileFixture = 'small.json'")
    rowof("a.txt").locator(".half").first.dblclick()
    page.wait_for_selector(".viewer", timeout=30_000)
    c = calls("compare_files")[-1]
    check("doppio clic su un file: confronto in un nuovo tab", c["left"] == "/o/uno/a.txt" and c["right"] == "/o/due/a.txt" and page.locator(".doctab").count() == n_tabs + 1, str(c))
    page.evaluate("window.__calls.length = 0; window.__recStatus = 'identical'")
    page.locator(".doctab-label").nth(1).click()
    page.wait_for_selector(".dir-preview")
    page.wait_for_function("window.__calls.some(c => c.cmd === 'recompare_entry')")
    check("tornando all'anteprima la riga già confrontata viene riconfrontata", True)
    check("nessun errore in console (anteprima)", not errors, "; ".join(errors[:3]))
    ctx.close()

    print("== Anteprima: dimensione delle cartelle, attesa e errore ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    page.evaluate("window.__sizeHold = true")
    page.evaluate("window.__pick = '/d/dir1'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/d/dir1'")
    page.evaluate("window.__pick = '/d/dir2'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_function("document.querySelectorAll('.dir-preview .dir-body .vl-row').length >= 2")
    page.wait_for_function("(window.__sizeCalls || []).length >= 1")
    sub = page.locator(".dir-preview .dir-body .dir-row", has_text="sub").first
    check("finché il calcolo non finisce la cartella mostra «…»", sub.locator(".dir-size").first.inner_text().strip() == "…")
    check("i file hanno già la loro dimensione", "1.2 KB" in page.locator(".dir-preview .dir-body .dir-row", has_text="a.txt").first.inner_text())
    page.evaluate("window.__sizeHold = false; window.__sizeRelease && window.__sizeRelease()")
    page.wait_for_function("(Array.from(document.querySelectorAll('.dir-preview .dir-row')).find(r => r.textContent.includes('sub'))?.querySelectorAll('.dir-size')[0].textContent.trim() ?? '…') !== '…'", timeout=10_000)
    # The second folder makes the sizes restart (new epoch), so the row can be redrawn after the wait above on a slow
    # machine: let the requests settle, then wait again before reading.
    page.wait_for_timeout(500)
    try:
        page.wait_for_function("(Array.from(document.querySelectorAll('.dir-preview .dir-row')).find(r => r.textContent.includes('sub'))?.querySelectorAll('.dir-size')[0].textContent.trim() ?? '…') !== '…'", timeout=10_000)
    except Exception:
        pass
    check("rilasciato il calcolo compare la dimensione", sub.locator(".dir-size").first.inner_text().strip() != "…")
    ctx.close()
    ctx, page, errors = open_page(browser, kind="dirs")
    page.evaluate("window.__sizeFail = true")
    page.evaluate("window.__pick = '/d/dir1'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/d/dir1'")
    page.evaluate("window.__pick = '/d/dir2'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_function("(window.__sizeCalls || []).length >= 2")
    page.wait_for_timeout(300)
    sub = page.locator(".dir-preview .dir-body .dir-row", has_text="sub").first
    check("calcolo fallito: nessun «…» che resta e nessun errore a schermo", sub.locator(".dir-size").first.inner_text().strip() == "" and page.locator(".error").count() == 0)
    ctx.close()

    print("== Anteprima: barra degli strumenti ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    page.evaluate("window.__pick = '/t/a'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/t/a'")
    page.evaluate("window.__pick = '/t/b'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_function("document.querySelectorAll('.dir-preview .dir-body .vl-row').length >= 2")
    calls = lambda c: page.evaluate("(c) => window.__calls.filter(x => x.cmd === c).map(x => x.args)", c)
    bar = page.locator(".dir-preview .dirbar")
    btn = lambda name: bar.get_by_role("button", name=name, exact=True)
    rows = page.locator(".dir-preview .dir-body .dir-row")
    ptext = lambda: page.inner_text(".dir-preview")
    n_cmp = lambda: len(calls("compare_directories")) + len(calls("recompare_entry")) + len(calls("compare_files"))
    no_compare = lambda: n_cmp() == 0
    check("la barra dell'anteprima ha Espandi, Comprimi e Refresh, e non più Swap (sta tra i campi)", bar.count() == 1 and all(btn(n).count() == 1 for n in ["Espandi", "Comprimi", "Refresh"]) and btn("Swap").count() == 0)
    # the two folders are read with separate calls: we wait for the list to be complete (and still) before counting it
    try:
        page.wait_for_function("document.querySelectorAll('.dir-preview .dir-body .dir-row').length === 2 && /sub/.test(document.querySelector('.dir-preview .dir-body').innerText) && /a\\.txt/.test(document.querySelector('.dir-preview .dir-body').innerText)", timeout=10000)
    except Exception:
        pass
    first_level = (rows.count(), "inner.txt" in ptext())
    check("prima di Espandi si vedono solo le voci del primo livello", first_level == (2, False),
          f"righe {first_level[0]}, inner.txt visibile: {first_level[1]}; {' | '.join(t.replace(chr(10), ' ') for t in rows.all_inner_texts())[:200]}")
    # compact bar (View menu) in the preview: one row, icons only, summary inside the bar
    page.wait_for_function("document.querySelector('.dir-preview .toolbar .dir-pills .stat.notCompared')")
    pvs = page.locator(".dir-preview .dirbar .view-switch .seg-btn")
    check("nell'anteprima Unificato è disattivato (con il suggerimento) e la Mappa è attiva",
          pvs.count() == 3 and pvs.nth(1).is_disabled() and "dopo aver confrontato" in pvs.nth(1).get_attribute("title") and pvs.nth(2).is_enabled())
    toggle_c = lambda: (page.click('.menu-title:has-text("Vista")'), page.click('.menu-panel button:has-text("Barra strumenti compatta")'))
    h_normal = bar.bounding_box()["height"]
    toggle_c()
    page.wait_for_selector(".dir-preview .dirbar.tb-compact")
    pill_c = page.locator(".dir-preview .dirbar > .summary .dir-pills .stat.notCompared")
    check("anteprima compatta: il riepilogo è dentro la barra e non c'è la riga a parte, con solo pallino e numero",
          page.locator(".dir-preview .summary-row").count() == 0 and pill_c.count() == 1 and pill_c.inner_text().strip() == "2" and "non confrontati" in pill_c.get_attribute("aria-label"), pill_c.inner_text() if pill_c.count() else "")
    cmp_btns = bar.locator(".dir-tools .merge-btn, .refresh-btn")
    check("anteprima compatta: Espandi, Comprimi e Refresh solo icona (32 px), Tipi senza parola ma con nome",
          [x.inner_text().strip() for x in cmp_btns.all()] == ["", "", ""] and all(round(x.bounding_box()["width"]) == 32 for x in cmp_btns.all())
          and bar.locator('button[aria-label="Tipi"] .tb-label').is_hidden() and bar.locator('button[aria-label="Tipi"]').count() == 1 and bar.locator(".opts-button", has_text="Altri filtri").count() == 1,
          f"{[x.inner_text().strip() for x in cmp_btns.all()]} {[x.bounding_box()['width'] for x in cmp_btns.all()]} {bar.locator('.opts-button', has_text='Tipi').count()} {bar.locator('button[aria-label=Types]').count()}")
    check("anteprima compatta: la barra resta su una riga", bar.bounding_box()["height"] < h_normal * 1.3 and bar.evaluate("e => e.querySelector('.refresh-btn').getBoundingClientRect().right") > bar.evaluate("e => e.querySelector('.summary').getBoundingClientRect().right"), str(bar.bounding_box()))
    toggle_c()
    page.wait_for_selector(".dir-preview .summary-row")
    check("tolta la compatta, torna il riepilogo sotto la barra", "tb-compact" not in bar.get_attribute("class"))
    check("la scansione conta anche le voci delle cartelle ancora chiuse: «non confrontati» include inner.txt, che non si vede",
          " ".join(page.locator(".dir-preview .toolbar .dir-pills .stat.notCompared").inner_text().split()) == "2 non confrontati" and page.locator(".dir-preview .toolbar .scan-note").count() == 0 and len(page.evaluate("window.__scanCalls || []")) == 1,
          page.locator(".dir-preview .toolbar .dir-pills").inner_text())
    btn("Espandi").click()
    page.wait_for_function("document.querySelector('.dir-preview').textContent.includes('inner.txt')")
    check("Espandi apre le cartelle (legge anche quelle interne)", rows.count() == 3)
    check("Espandi non confronta niente", no_compare())
    btn("Comprimi").click()
    page.wait_for_timeout(200)
    check("Comprimi richiude tutto", rows.count() == 2 and "inner.txt" not in ptext())
    # Swap: the sides are swapped without comparing and without rereading what is already known
    btn("Espandi").click()
    page.wait_for_function("document.querySelector('.dir-preview').textContent.includes('inner.txt')")
    # the summary is there even before comparing: pills with the counts and "not compared"
    pills = page.locator(".dir-preview .toolbar .dir-pills")
    num = lambda k: int(pills.locator(f".stat.{k} strong").inner_text()) if pills.locator(f".stat.{k}").count() else 0
    n0, i0 = num("notCompared"), num("identical")
    check("anteprima: prima di confrontare il riepilogo c'è e ha le coppie di file «non confrontati»", pills.count() == 1 and n0 >= 1 and i0 == 0 and "non confrontati" in pills.inner_text(), pills.inner_text() if pills.count() else "nessun riepilogo")
    page.locator(".dir-preview .toolbar").first.screenshot(path=f"{SHOTS}/preview_summary.png")
    check("«non confrontati» ha il pallino vuoto e il suggerimento dice «non ancora confrontate»", "non ancora confrontat" in pills.locator(".stat.notCompared").get_attribute("title"))
    # a mark already computed: it must stay after Swap and disappear after Refresh
    a_mark = lambda: page.locator(".dir-preview .dir-body .dir-row", has_text="a.txt").first.locator(".dir-mark").inner_text().strip()
    page.locator(".dir-preview .dir-body .dir-row", has_text="a.txt").first.locator(".half").first.click()
    page.locator('.tabpage:not([hidden]) .paths button.primary').click()
    page.wait_for_function("Array.from(document.querySelectorAll('.dir-preview .dir-row')).find(r => r.textContent.includes('a.txt')).querySelector('.dir-mark').textContent.trim() === '='")
    check("dopo aver confrontato a.txt: un identico in più e un «non confrontato» in meno", num("identical") == i0 + 1 and num("notCompared") == n0 - 1, f"{num('identical')} {num('notCompared')} da {i0} {n0}")
    base = n_cmp()
    n_list = len(calls("list_directory"))
    page.locator(".tabpage:not([hidden]) .swap-btn").click()
    page.wait_for_timeout(400)
    fl, fr = page.input_value('input[aria-label="Sinistra"]'), page.input_value('input[aria-label="Destra"]')
    check("Swap scambia i due percorsi", fl == "/t/b" and fr == "/t/a", f"{fl} | {fr}")
    check("Swap non confronta e tiene aperte le cartelle", n_cmp() == base and rows.count() == 3 and "inner.txt" in ptext())
    check("Swap tiene il segno già calcolato", a_mark() == "=", a_mark())
    check("Swap riusa il contenuto già letto (nessuna lettura nuova)", len(calls("list_directory")) == n_list, f"{len(calls('list_directory'))} contro {n_list}")
    # Refresh: rereads, keeps the openings
    btn("Refresh").click()
    page.wait_for_function("(n) => window.__calls.filter(c => c.cmd === 'list_directory').length > n", arg=n_list)
    page.wait_for_function("document.querySelector('.dir-preview').textContent.includes('inner.txt')")
    check("Refresh rilegge le cartelle e tiene quelle aperte", rows.count() == 3 and len(calls("list_directory")) > n_list)
    check("Refresh non confronta niente", n_cmp() == base)
    check("Refresh azzera il segno già calcolato", a_mark() == "", a_mark())
    check("Refresh rifà la scansione", len(page.evaluate("window.__scanCalls || []")) >= 2)
    page.evaluate("window.__scanHold = true")
    btn("Refresh").click()
    page.wait_for_function("document.querySelector('.dir-preview .toolbar .scan-note')")
    check("mentre la scansione è in corso lo dice e mostra intanto i conteggi delle voci già lette", "in corso" in page.locator(".dir-preview .toolbar .scan-note").inner_text() and page.locator(".dir-preview .toolbar .dir-pills .stat.identical").count() == 0)
    page.evaluate("window.__scanHold = false; window.__scanRelease && window.__scanRelease()")
    page.wait_for_function("!document.querySelector('.dir-preview .toolbar .scan-note')")
    page.evaluate("window.__scanTruncate = 7")
    btn("Refresh").click()
    page.wait_for_function("document.querySelector('.dir-preview .toolbar .scan-note')")
    check("se la scansione si ferma al limite lo dice: conteggi parziali", "fermato a 7 voci" in page.locator(".dir-preview .toolbar .scan-note").inner_text(), page.locator(".dir-preview .toolbar .scan-note").inner_text())
    page.evaluate("window.__scanTruncate = 0")
    check("nessun errore in console (barra dell'anteprima)", not errors, "; ".join(errors[:3]))
    ctx.close()

    print("== Anteprima: filtri ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    page.evaluate("window.__pick = '/o/uno'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/o/uno'")
    page.evaluate("window.__pick = '/o/due'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_function("document.querySelectorAll('.dir-preview .dir-body .vl-row').length >= 3")
    bar = page.locator(".dir-preview .dirbar")
    fbtn = lambda n: bar.locator(f'.seg-btn:has-text("{n}"), .opts-button:has-text("{n}")').first
    rows = page.locator(".dir-preview .dir-body .dir-row")
    rtext = lambda: " | ".join(t.replace("\n", " ") for t in rows.all_inner_texts())
    rnames = lambda: rows.evaluate_all("els => els.flatMap(e => [...e.querySelectorAll('.dir-name')].map(n => n.textContent.trim()))")
