"""App shell: files and errors, version, menus, Home, title, languages, tabs, wheel. A suite of the UI test (see README.md in this folder)."""
from harness import *


def run(browser):
    # ------------------------------------------------------------------ picker and errors
    print("== Selettore di file ed errori ==")
    ctx, page, errors = open_page(browser)
    page.evaluate("window.__pick = '/home/utente/scelto.txt'")
    page.locator('.path-field .browse-btn').first.click()
    page.wait_for_timeout(200)
    check("Sfoglia (sinistra) riempie il campo", page.input_value('input[aria-label="Sinistra"]') == "/home/utente/scelto.txt")
    check("selettore file: directory=false", page.evaluate(
        "window.__calls.some(c => c.cmd==='plugin:dialog|open' && c.args.options.directory===false)"))
    page.evaluate("window.__pick = null")  # cancelled
    page.locator('.path-field .browse-btn').nth(1).click()
    page.wait_for_timeout(200)
    check("selezione annullata: il campo resta com'era", page.input_value('input[aria-label="Destra"]') == "")
    page.locator(".doctab-add").click()
    page.click('.chooser .card:has-text("Cartelle")')
    page.evaluate("window.__pick = '/home/utente/cartella'")
    page.locator('.tabpage:not([hidden]) .path-field .browse-btn').nth(1).click()
    page.wait_for_timeout(200)
    check("Sfoglia (destra, cartelle) riempie il campo", page.input_value('.tabpage:not([hidden]) input[aria-label="Destra"]') == "/home/utente/cartella")
    check("selettore cartelle: directory=true", page.evaluate(
        "window.__calls.filter(c => c.cmd==='plugin:dialog|open').slice(-1)[0].args.options.directory===true"))

    page.locator(".doctab-label").nth(1).click()
    page.fill('input[aria-label="Sinistra"]', "/x/manca.txt")
    page.fill('input[aria-label="Destra"]', "/x/b.txt")
    page.evaluate("window.__fail = 'impossibile leggere /x/manca.txt: No such file or directory'")
    page.click('button[type="submit"]')
    page.wait_for_selector(".error", timeout=5000)
    check("errore del comando mostrato all'utente", "manca.txt" in page.inner_text(".error"), page.inner_text(".error"))
    page.screenshot(path=f"{SHOTS}/11_error.png")
    page.evaluate("window.__fail = null")
    page.fill('input[aria-label="Sinistra"]', "")
    page.click('button[type="submit"]')
    check("percorsi mancanti: messaggio", "entrambi i percorsi" in page.inner_text(".error"))
    check("nessun errore in console (selettore)", not errors, "; ".join(errors[:3]))
    ctx.close()

    # ------------------------------------------------------------------ menus, options, report
    print("== Versione e informazioni sulla build ==")
    ctx, page, errors = open_page(browser, kind=None)
    line = page.locator(".home .build-line").inner_text().strip()
    check("la Home mostra versione, commit e data con l'orario",
          re.match(r"^Versione 0\.1\.0( · [0-9a-f]{7,}\*?)? · compilata il \d{1,2} \w+ \d{4}, \d{2}:\d{2}$", line) is not None, line)
    below = page.evaluate("() => document.querySelector('.home .build-line').getBoundingClientRect().top >= document.querySelector('.home .tips').getBoundingClientRect().bottom - 1")
    check("e sta in fondo alla Home, sotto tutto il resto", below)
    right = page.evaluate("() => { const b = document.querySelector('.home .build-line button').getBoundingClientRect(), f = document.querySelector('.home-foot').getBoundingClientRect(); return [Math.round(f.right - b.right), Math.round(b.left - f.left)]; }")
    check("ed è allineata a destra", right[0] <= 1 and right[1] > 100, str(right))
    geo = page.evaluate("""() => {
      const t = document.querySelector('.home-title'), s = t.querySelector('svg').getBoundingClientRect(), h = t.querySelector('h1').getBoundingClientRect(), b = t.getBoundingClientRect();
      return { right: s.right, hLeft: h.left, dy: Math.abs((s.top + s.bottom) / 2 - (b.top + b.bottom) / 2), w: s.width };
    }""")
    check("l'icona (quella di sempre, 72 px) sta a sinistra del titolo, centrata sul blocco titolo e frase", geo["right"] <= geo["hLeft"] and geo["dy"] < 4 and 68 <= geo["w"] <= 76, str(geo))
    ids = page.evaluate("[...document.querySelectorAll('svg linearGradient')].map(g => g.id)")
    check("ogni logo ha un gradiente con identificativo proprio", len(ids) == len(set(ids)) and all(i.startswith("logo-bg-") for i in ids), str(ids))
    page.locator(".home .build-line button").click()
    page.wait_for_selector(".modal .about-info")
    labels = page.locator(".about-info dt").all_inner_texts()
    check("un clic apre «Informazioni» con il dettaglio",
          labels[:4] == ["Versione", "Commit", "Compilata il", "Tipo di build"] and "Motore della finestra" in labels and "Sistema" in labels, str(labels))
    vals = dict(zip(labels, page.locator(".about-info dd").all_inner_texts()))
    check("una build è «rilascio» e ha la versione", vals.get("Tipo di build") == "rilascio" and vals.get("Versione") == "0.1.0", str(vals))
    check("il commit c'è, oppure dice che non è noto", re.match(r"^([0-9a-f]{7,}\*?.*|sconosciuto.*)$", vals.get("Commit", "")) is not None, vals.get("Commit", ""))
    page.screenshot(path=f"{SHOTS}/about_build.png")
    page.keyboard.press("Escape")
    check("nessun errore in console (informazioni sulla build)", not errors, "; ".join(errors[:3]))
    ctx.close()

    print("== Barra dei menu, opzioni e report ==")
    ctx, page, errors = open_page(browser, kind=None)
    titles = page.locator(".menu-title").all_inner_texts()
    check("la barra ha File, Modifica, Vista, Strumenti, Aiuto", titles == ["File", "Modifica", "Vista", "Strumenti", "Aiuto"], str(titles))
    page.click('.menu-title:has-text("Modifica")')
    check("nella Home le voci di Modifica sono tutte spente (il tab non offre comandi)",
          page.locator(".menu-panel button").count() == 4 and page.locator(".menu-panel button:not(:disabled)").count() == 0)
    page.keyboard.press("Escape")
    for title in titles:
        page.click(f'.menu-title:has-text("{title}")')
        h = page.evaluate("""() => [...document.querySelectorAll('.menu-panel .menu-label')].map(e => Math.round(e.getBoundingClientRect().height))""")
        check(f"menu {title}: nessuna voce va a capo", len(h) > 0 and max(h) <= min(h) + 1, str(h))
        page.keyboard.press("Escape")
    page.click('.menu-title:has-text("File")')
    check("un clic apre il menu", page.locator(".menu-panel").count() == 1 and "Nuovo tab" in page.inner_text(".menu-panel"))
    page.hover('.menu-title:has-text("Vista")')
    check("passando su un altro titolo si cambia menu", "Tema" in page.inner_text(".menu-panel") and "Testo più grande" in page.inner_text(".menu-panel"))
    page.keyboard.press("ArrowRight")
    check("freccia destra: menu successivo", "Opzioni" in page.inner_text(".menu-panel"))
    page.keyboard.press("Escape")
    check("Esc chiude il menu", page.locator(".menu-panel").count() == 0)
    # a submenu: the mouse over the item opens it, and a click that comes later (a person rests on it first) must not close it
    page.click('.menu-title:has-text("Vista")')
    page.hover('.menu-panel button:has-text("Tema")')
    page.wait_for_selector(".menu-panel.submenu")
    page.wait_for_timeout(300)
    page.click('.menu-panel button:has-text("Tema")')
    check("un clic su «Tema» dopo il passaggio del mouse non chiude il sottomenu", page.locator(".menu-panel.submenu").count() == 1)
    page.focus('.menu-panel button:has-text("Tema")')
    page.keyboard.press("ArrowRight")
    check("freccia destra con il sottomenu già aperto dal mouse porta il focus dentro",
          page.evaluate("document.activeElement.closest('.menu-panel.submenu') !== null"))
    page.keyboard.press("ArrowLeft")
    check("freccia sinistra torna alla voce «Tema»", page.evaluate("document.activeElement.dataset.submenu") == "Tema" and page.locator(".menu-panel.submenu").count() == 0)
    page.keyboard.press("Escape")
    page.click('.menu-title:has-text("File")')
    page.mouse.click(600, 500)
    check("un clic fuori chiude il menu", page.locator(".menu-panel").count() == 0)
    page.screenshot(path=f"{SHOTS}/18_menu_closed.png")
    page.click('.menu-title:has-text("File")')
    page.screenshot(path=f"{SHOTS}/19_menu_open.png")
    page.click('.menu-panel button:has-text("Nuovo confronto di cartelle")')
    check("File > Nuovo confronto di cartelle apre un tab di cartelle", page.locator(".menu-panel").count() == 0
          and page.locator(".doctab").count() == 2 and page.locator('.tabpage:not([hidden]) input[aria-label="Sinistra"]').count() == 1
          and "cartella" in page.get_attribute('.tabpage:not([hidden]) input[aria-label="Sinistra"]', "placeholder"))
    page.keyboard.press("Control+w")
    check("Ctrl+W chiude il tab, ma non la Home", page.locator(".doctab").count() == 1)
    page.keyboard.press("Control+w")
    check("la Home resta", page.locator(".doctab").count() == 1 and page.locator(".home").is_visible())

    # theme
    bg = lambda: page.evaluate("getComputedStyle(document.body.parentElement).backgroundColor")
    light_bg = bg()

    def theme_menu(label):
        """View > Theme > label: the three themes are in a submenu."""
        page.click('.menu-title:has-text("Vista")')
        page.click('.menu-panel button:has-text("Tema")')
        page.click(f'.menu-panel.submenu button:has-text("{label}")')

    theme_menu("Scuro")
    check("Tema scuro: attributo e colori", page.evaluate("document.documentElement.dataset.theme") == "dark" and bg() != light_bg, bg())
    page.click('.menu-title:has-text("Vista")')
    page.click('.menu-panel button:has-text("Tema")')
    check("il tema sta in un sottomenu; la voce del tema attivo ha il segno",
          page.locator(".menu-panel.submenu").count() == 1 and "✓" in page.locator('.menu-panel.submenu button:has-text("Scuro")').inner_text()
          and "✓" not in page.locator('.menu-panel.submenu button:has-text("Chiaro")').inner_text())
    check("nel menu Vista non ci sono più le tre voci del tema in fila", page.locator('.menu-panel > .menu-item > button:has-text("Tema scuro")').count() == 0)
    page.keyboard.press("Escape")
    page.reload()
    check("il tema resta dopo il riavvio", page.evaluate("document.documentElement.dataset.theme") == "dark")
    page.screenshot(path=f"{SHOTS}/20_theme_dark_home.png")
    theme_menu("Chiaro")
    check("Tema chiaro", page.evaluate("document.documentElement.dataset.theme") == "light" and bg() == light_bg)
    theme_menu("Automatico")
    check("Tema automatico toglie l'attributo", page.evaluate("document.documentElement.dataset.theme") is None)
    # text size
    page.click('.menu-title:has-text("Vista")'); page.click('.menu-panel button:has-text("Testo più grande")')
    check("Testo più grande: 14px", page.evaluate("document.documentElement.style.getPropertyValue('--code-size')") == "14px")
    size = lambda: page.evaluate("document.documentElement.style.getPropertyValue('--code-size')")
    for _ in range(2):
        page.click('.menu-title:has-text("Vista")'); page.click('.menu-panel button:has-text("Testo più grande")')
    check("il testo ha un massimo (16px)", size() == "16px")
    page.click('.menu-title:has-text("Vista")')
    check("al massimo «Testo più grande» è spenta, le altre due no",
          page.locator('.menu-panel button:has-text("Testo più grande")').is_disabled()
          and page.locator('.menu-panel button:has-text("Testo più piccolo")').is_enabled() and page.locator('.menu-panel button:has-text("Dimensione normale")').is_enabled())
    check("le voci della dimensione mostrano le scorciatoie",
          [x.strip() for x in page.locator(".menu-panel .menu-shortcut").all_inner_texts()] == ["Ctrl+B", "Ctrl++", "Ctrl+-", "Ctrl+0"], str(page.locator(".menu-panel .menu-shortcut").all_inner_texts()))
    page.keyboard.press("Escape")
    page.keyboard.press("Control+0")
    check("Ctrl+0 riporta alla dimensione normale (13px)", size() == "13px", size())
    page.keyboard.press("Control+Minus")
    check("Ctrl+- riduce di un passo", size() == "12px", size())
    page.keyboard.press("Control+Equal")
    page.keyboard.press("Control+Shift+Equal")
    check("Ctrl+= e Ctrl++ ingrandiscono di un passo ciascuno", size() == "14px", size())
    for _ in range(5):
        page.keyboard.press("Control+Equal")
    check("con la tastiera il testo si ferma ai limiti (16px)", size() == "16px", size())
    page.click('.menu-title:has-text("Vista")')
    check("«Dimensione normale» si spegne quando il testo è già normale",
          (page.keyboard.press("Escape") or True) and (page.keyboard.press("Control+0") or True) and size() == "13px"
          and (page.click('.menu-title:has-text("Vista")') or True) and page.locator('.menu-panel button:has-text("Dimensione normale")').is_disabled())
    page.keyboard.press("Escape")

    # options
    page.click('.menu-title:has-text("Strumenti")'); page.click('.menu-panel button:has-text("Opzioni")')
    check("Strumenti > Opzioni apre la finestra", page.locator('.modal[aria-label="Opzioni"]').is_visible())
    page.screenshot(path=f"{SHOTS}/21_options.png")
    page.locator('.modal label.check:has-text("Ignora maiuscole") input').check()
    page.locator('.modal label:has-text("Elenco dei confronti di cartelle") select').select_option("all")
    page.locator('.modal input[type=number]').fill("12")
    check("la dimensione del testo si applica subito", page.evaluate("document.documentElement.style.getPropertyValue('--code-size')") == "12px")
    # Git: the options write (or take out) the configuration
    git = page.locator(".modal .git-setup")
    git_calls = lambda c: page.evaluate("(c) => window.__calls.filter(x => x.cmd === c).map(x => x.args)", c)
    page.wait_for_function("window.__calls.some(c => c.cmd === 'git_status')")
    check("le opzioni hanno la parte Git: dice che Git non è configurato e «Togli» è spento",
          git.count() == 1 and "Git non è configurato per NurDiff" in git.inner_text() and git.locator("button", has_text="Togli").is_disabled(), git.inner_text()[:120])
    git.locator("button", has_text="Configura Git").click()
    page.wait_for_function("window.__calls.some(c => c.cmd === 'git_setup')")
    check("«Configura Git» chiama git_setup senza diff.external e dice quante impostazioni ha scritto",
          git_calls("git_setup")[-1]["external"] is False and "Fatto: 3 impostazioni scritte" in git.inner_text(), git.inner_text()[-80:])
    check("poi lo stato diventa «configurato» e «Togli» si accende", "«git difftool» apre NurDiff" in git.inner_text() and git.locator("button", has_text="Togli").is_enabled())
    git.locator("label.check", has_text="Anche per «git diff»").locator("input").check()
    git.locator("button", has_text="Configura Git").click()
    page.wait_for_function("window.__calls.filter(c => c.cmd === 'git_setup').length === 2")
    check("con la casella «Anche per git diff» scrive anche diff.external", git_calls("git_setup")[-1]["external"] is True and "Fatto: 4 impostazioni scritte" in git.inner_text() and "Anche «git diff»" in git.inner_text())
    git.locator("label.check", has_text="git mergetool").locator("input").check()
    git.locator("button", has_text="Configura Git").click()
    page.wait_for_function("window.__calls.filter(c => c.cmd === 'git_setup').length === 3")
    check("con la casella «Anche per git mergetool» scrive anche lo strumento di merge (3 voci in più)",
          git_calls("git_setup")[-1]["mergetool"] is True and "Fatto: 7 impostazioni scritte" in git.inner_text() and "Anche «git mergetool»" in git.inner_text(), git.inner_text()[-120:])
    git.locator("button", has_text="Togli").click()
    page.wait_for_function("window.__calls.some(c => c.cmd === 'git_remove')")
    check("«Togli» chiama git_remove e lo stato torna a non configurato", "Tolte: 2 impostazioni" in git.inner_text() and "Git non è configurato per NurDiff" in git.inner_text())
    page.evaluate("window.__gitFail = { code: 'err.git.noCli', params: {} }")
    git.locator("button", has_text="Configura Git").click()
    page.wait_for_selector(".modal .git-setup .error")
    check("se la CLI non si trova, l'errore è tradotto e visibile", "nurdiff-cli non si trova accanto" in git.locator(".error").inner_text(), git.locator(".error").inner_text())
    page.evaluate("window.__gitFail = null")
    page.keyboard.press("Escape")
    check("Esc chiude la finestra", page.locator(".modal").count() == 0)
    page.reload()
    page.click('.home button.card:has-text("Confronta file")')
    check("un nuovo confronto di file parte con «Ignora maiuscole» come da opzioni",
          page.locator('.tabpage:not([hidden]) label.check:has-text("Ignora maiuscole") input').is_checked()
          and page.locator('.tabpage:not([hidden]) label:has-text("Ignora spazi") select').input_value() == "none")
    page.evaluate("window.__load('small.json')")
    page.fill('.tabpage:not([hidden]) input[aria-label="Sinistra"]', "/x/a.txt")
    page.fill('.tabpage:not([hidden]) input[aria-label="Destra"]', "/x/b.txt")
    page.click('.tabpage:not([hidden]) button[type="submit"]')
    page.wait_for_selector(".viewer", timeout=30_000)
    check("e lo passa al confronto", page.evaluate("window.__calls.filter(c => c.cmd==='compare_files').slice(-1)[0].args.ignoreCase") is True)
    check("la dimensione del testo vale nei pannelli", page.evaluate("getComputedStyle(document.querySelector('.pane.right')).fontSize") == "12px")

    # report of a file comparison
    page.click('.menu-title:has-text("Strumenti")')
    check("con un confronto aperto «Report» è abilitato", page.locator('.menu-panel button:has-text("Report")').is_enabled())
    page.click('.menu-panel button:has-text("Report")')
    check("si apre la finestra del report con i formati dei file", page.locator('.modal[aria-label="Report del confronto"]').is_visible()
          and "Diff unificato" in page.inner_text(".modal"))
    page.screenshot(path=f"{SHOTS}/22_report.png")
    page.click('.modal button:has-text("Salva")')
    page.wait_for_selector(".modal .notice", timeout=5000)
    ex = page.evaluate("window.__calls.filter(c => c.cmd==='export_file_report').slice(-1)[0].args")
    check("salva l'HTML con 3 righe di contesto", ex["format"] == "html" and ex["context"] == 3 and ex["path"] == "/out/report.html"
          and ex["id"] > 100, str(ex))
    check("dice dove ha salvato", "/out/report.html" in page.inner_text(".modal .notice"))
    sv = page.evaluate("window.__calls.filter(c => c.cmd==='plugin:dialog|save').slice(-1)[0].args")
    check("la finestra di salvataggio propone un nome e l'estensione", sv["options"]["defaultPath"] == "nurdiff-report.html"
          and sv["options"]["filters"][0]["extensions"] == ["html"], str(sv))
    # copy: the same report goes to the clipboard, without asking where to save it
    ctx.grant_permissions(["clipboard-read", "clipboard-write"])
    clip = lambda: page.evaluate("navigator.clipboard.readText()")
    n_dialogs = len(page.evaluate("window.__calls.filter(c => c.cmd==='plugin:dialog|save')"))
    page.click('.modal button:has-text("Copia")')
    page.wait_for_function("document.querySelector('.modal .notice')?.textContent.includes('copiato')", timeout=5000)
    cp = page.evaluate("window.__calls.filter(c => c.cmd==='file_report_text').slice(-1)[0].args")
    check("«Copia» chiede al core lo stesso report (HTML, 3 righe di contesto) e lo mette negli appunti",
          cp["format"] == "html" and cp["context"] == 3 and clip() == "REPORT html 3" and "copiato negli appunti" in page.inner_text(".modal .notice"), f"{cp} {clip()!r}")
    check("copiare non apre la finestra di salvataggio e non scrive file",
          len(page.evaluate("window.__calls.filter(c => c.cmd==='plugin:dialog|save')")) == n_dialogs
          and page.evaluate("window.__calls.filter(c => c.cmd==='export_file_report').length") == 1)
    page.evaluate("window.__fail = 'errore simulato del core'")
    page.click('.modal button:has-text("Copia")')
    page.wait_for_selector(".modal .error", timeout=5000)
    check("se il core non riesce, l'errore è mostrato e gli appunti non cambiano", "errore simulato" in page.inner_text(".modal .error") and clip() == "REPORT html 3")
    page.evaluate("window.__fail = null")
    page.locator('.modal input[type=radio]').nth(1).check()
    page.locator('.modal select').select_option("all")
    page.click('.modal button:has-text("Copia")')
    page.wait_for_function("navigator.clipboard.readText().then(t => t === 'REPORT unified null')", timeout=5000)
    check("con il diff unificato e tutto il file, copia quel formato", True)
    page.evaluate("window.__savePath = '/out/p.diff'")
    page.click('.modal button:has-text("Salva")')
    page.wait_for_function("window.__calls.filter(c => c.cmd==='export_file_report').length === 2")
    ex = page.evaluate("window.__calls.filter(c => c.cmd==='export_file_report').slice(-1)[0].args")
    check("diff unificato di tutto il file", ex["format"] == "unified" and ex["context"] is None and ex["path"] == "/out/p.diff", str(ex))
    page.evaluate("window.__savePath = null")
    n = page.evaluate("window.__calls.filter(c => c.cmd==='export_file_report').length")
    page.click('.modal button:has-text("Salva")')
    page.wait_for_timeout(300)
    check("annullando la finestra di salvataggio non si scrive nulla", page.evaluate("window.__calls.filter(c => c.cmd==='export_file_report').length") == n)
    page.evaluate("window.__savePath = '/out/x.html'; window.__fail = 'impossibile scrivere /out/x.html: permesso negato'")
    page.click('.modal button:has-text("Salva")')
    page.wait_for_selector(".modal .error", timeout=5000)
    check("un errore di scrittura è mostrato nella finestra", "permesso negato" in page.inner_text(".modal .error"))
    page.evaluate("window.__fail = null")
    page.keyboard.press("Escape")

    # folder report
    page.locator(".doctab-add").click()
    page.click('.chooser .card:has-text("Cartelle")')
    page.click('.menu-title:has-text("Strumenti")')
    check("in un tab senza confronto «Report» è disabilitato", page.locator('.menu-panel button:has-text("Report")').is_disabled())
    page.keyboard.press("Escape")
    page.fill('.tabpage:not([hidden]) input[aria-label="Sinistra"]', "/x/l")
    page.fill('.tabpage:not([hidden]) input[aria-label="Destra"]', "/x/r")
    page.click('.tabpage:not([hidden]) button[type="submit"]')
    page.wait_for_selector(".dir-body .vl-row", timeout=60_000)
    check("l'elenco delle cartelle si apre col filtro delle opzioni (Tutto)", page.locator(".tabpage:not([hidden]) .dirbar .dir-filters .seg-btn[aria-pressed='true']").inner_text().strip().endswith("Tutte"))
    page.evaluate("window.__savePath = '/out/dirs.html'")
    page.click('.menu-title:has-text("Strumenti")'); page.click('.menu-panel button:has-text("Report")')
    check("i formati delle cartelle sono HTML e CSV", "CSV" in page.inner_text(".modal") and "Diff unificato" not in page.inner_text(".modal"))
    page.click('.modal button:has-text("Salva")')
    page.wait_for_selector(".modal .notice", timeout=5000)
    w = page.evaluate("window.__calls.filter(c => c.cmd==='write_text_file').slice(-1)[0].args")
    check("scrive la pagina HTML delle differenze", w["path"] == "/out/dirs.html" and w["contents"].startswith("<!doctype html>")
          and "Confronto di cartelle" in w["contents"] and "/x/l" in w["contents"], w["contents"][:80])
