"""Sidebar. A suite of the UI test (see README.md in this folder)."""
from harness import *


def run(browser):
    # ------------------------------------------------------------------ sidebar
    print("== Barra laterale: elenco delle differenze ==")
    ctx, page, errors = open_page(browser)
    calls_of = lambda c: page.evaluate("(c) => window.__calls.filter(x => x.cmd === c).map(x => x.args)", c)
    run_files(page, "small.json")
    hunks = page.evaluate("window.__fx['small.json'].opened.hunks")
    n = len(hunks)
    check("la barra laterale è chiusa di default e non occupa spazio", page.locator(".sidebar").count() == 0)
    page.keyboard.press("Control+b")
    page.wait_for_selector(".sidebar .sb-item")
    tab_names = page.locator(".sidebar .sb-tab").evaluate_all("els => els.map(e => e.getAttribute('aria-label'))")
    check("le icone della barra: prima «File della directory», poi «Differenze file»", tab_names == ["File della directory", "Differenze file"], str(tab_names))
    check("Ctrl+B la apre sulla vista «Differenze»", page.locator(".sidebar").is_visible() and "differenze" in page.inner_text(".sb-title").lower())
    check("larghezza iniziale 280 px", page.evaluate("document.querySelector('.sidebar').getBoundingClientRect().width") == 280)
    check("l'elenco è virtualizzato", 0 < page.locator(".sb-item").count() < 40, str(page.locator(".sb-item").count()))
    check("intestazione: numero di differenze", page.inner_text(".sb-title").replace("\n", " ").endswith(str(n)), page.inner_text(".sb-title"))
    check("in fondo alla barra non c'è più il piè di pagina «unite · da fare»", page.locator(".sb-foot").count() == 0)
    first_text = page.evaluate("(() => { const fx = window.__fx['small.json']; const r = fx.rows[fx.opened.hunks[0].start]; const c = r.left || r.right; return [c.number, c.text.trim()]; })()")
    page.wait_for_function("document.querySelector('.sb-item .sb-text').textContent.length > 0")
    check("ogni voce mostra numero di riga e testo", page.locator(".sb-item").first.locator(".sb-num").inner_text() == str(first_text[0])
          and page.locator(".sb-item").first.locator(".sb-text").inner_text() == first_text[1], str(first_text))
    page.locator(".sb-item").nth(5).click()
    check("un clic su una voce porta a quella differenza", f"Differenza 6 di {n}" in counter(page), counter(page))
    check("la voce corrente è evidenziata", page.locator(".sb-item.cur").count() == 1 and page.locator(".sb-title").inner_text().replace("\n", " ").startswith("DIFFERENZE FILE") )
    page.click('.tabpage:not([hidden]) button[aria-label="Successiva"]')
    page.wait_for_function("document.querySelector('.sb-title').textContent.includes('7 di')")
    check("la barra segue Successiva", f"7 di {n}" in page.evaluate("document.querySelector('.sb-title').textContent"), page.inner_text(".sb-title"))
    # filters by kind
    left_only = [i for i, h in enumerate(hunks) if h["kind"] == "leftOnly"]
    page.click('.sb-chip:has-text("Solo sx")')
    page.wait_for_timeout(200)
    check("il filtro «Solo sx» tiene solo i blocchi a sinistra", page.evaluate("document.querySelector('.sb-list > div').style.height") == f"{len(left_only) * 24}px",
          page.evaluate("document.querySelector('.sb-list > div').style.height"))
    page.locator(".sb-item").nth(1).click()
    check("e porta alla differenza giusta dell'elenco completo", f"Differenza {left_only[1] + 1} di {n}" in counter(page), counter(page))
    page.click('.sb-chip:has-text("Tutte")')
    # the panel is resized and remembers
    box = page.locator(".sb-resize").bounding_box()
    page.mouse.move(box["x"] + 3, box["y"] + 100); page.mouse.down(); page.mouse.move(box["x"] + 63, box["y"] + 100, steps=4); page.mouse.up()
    page.wait_for_timeout(150)
    w = page.evaluate("document.querySelector('.sidebar').getBoundingClientRect().width")
    check("trascinando il bordo la barra si allarga", 335 <= w <= 345, str(w))
    check("la larghezza si salva", page.evaluate("window.__cfg('state').width") == round(w))
    page.keyboard.press("Control+b")
    page.wait_for_timeout(150)
    check("Ctrl+B la richiude", page.locator(".sidebar").count() == 0 and page.evaluate("window.__cfg('state').open") is False)
    page.click(".sb-toggle")
    page.wait_for_selector(".sidebar")
    check("il pulsante nella barra dei tab la riapre", page.locator(".sidebar").is_visible())
    # after a merge the bar updates
    page.click('.tabpage:not([hidden]) button:has-text("Applica a sx")')
    page.wait_for_timeout(500)
    # state remembered at restart
    page.reload()
    page.wait_for_selector(".sidebar")
    check("al riavvio la barra è ancora aperta e larga uguale", page.evaluate("document.querySelector('.sidebar').getBoundingClientRect().width") == round(w))
    check("sulla Home «Differenze file» è disabilitata, col motivo nel suggerimento",
          page.locator('.sb-tab[aria-label="Differenze file"]').is_disabled()
          and "confronto di file" in (page.get_attribute('.sb-tab[aria-label="Differenze file"]', "title") or ""))
    check("sulla Home la barra mostra comunque la vista File, senza pannello vuoto", "Apri un confronto di cartelle" in page.inner_text(".sidebar"))
    page.click('.sb-tab[aria-label="File della directory"]')
    check("vista File senza un confronto di cartelle: messaggio", "Apri un confronto di cartelle" in page.inner_text(".sidebar"))
    check("nessun errore in console (barra laterale)", not errors, "; ".join(errors[:3]))
    page.screenshot(path=f"{SHOTS}/33_sidebar_files_empty.png")
    ctx.close()

    print("== Barra laterale: contenuto dell'anteprima ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    page.keyboard.press("Control+b")
    page.click('.sb-tab[aria-label="File della directory"]')
    check("con i campi vuoti la barra invita ad aprire un confronto", "Apri un confronto di cartelle" in page.inner_text(".sidebar"))
    page.evaluate("window.__pick = '/o/uno'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/o/uno'")
    page.evaluate("window.__pick = '/o/due'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_function("document.querySelectorAll('.sidebar .sb-item .sb-text').length >= 3")
    names = lambda: page.locator(".sidebar .sb-item .sb-text").all_inner_texts()
    check("prima del confronto la barra elenca il contenuto delle due cartelle", set(names()) == {"a.txt", "solo-sinistra.txt", "solo-destra.txt"}, str(names()))
    check("la barra dice che lo stato non è noto", "Non ancora confrontate" in page.inner_text(".sidebar"))
    check("nessun confronto è partito", len(page.evaluate("window.__calls.filter(c => c.cmd === 'compare_directories')")) == 0)
    item = lambda title: page.locator(f'.sidebar .sb-item[title="{title}"]')
    st = lambda n: item(n).locator(".sb-st")
    check("una voce presente da un lato solo ha la sua icona", st("solo-sinistra.txt").locator("svg").count() == 1 and st("solo-destra.txt").locator("svg").count() == 1)
    check("una voce presente da entrambi i lati non ha icona (stato ignoto)", st("a.txt").locator("svg").count() == 0)
    check("niente filtri in anteprima", page.locator(".sidebar .sb-chip").count() == 0)
    item("solo-sinistra.txt").click()
    check("un clic su una voce di un lato solo spiega perché non si apre", "esiste solo da un lato" in page.inner_text(".sidebar"))
    n_tabs = page.locator(".doctab").count()
    item("a.txt").click()
    page.wait_for_function("(n) => document.querySelectorAll('.doctab').length > n", arg=n_tabs)
    check("un clic su un file in comune lo apre in un nuovo tab", page.locator(".doctab").count() == n_tabs + 1)
    try:  # the bar updates after the tab opens: we wait for the highlighted entry instead of reading right away
        page.wait_for_selector(".sidebar .sb-item.cur", timeout=5_000)
    except Exception:
        pass
    check("nel tab del file la barra mostra le differenze del confronto, non l'anteprima", page.evaluate("window.__cfg('state').view") == "diffs" and "solo-destra.txt" not in page.inner_text(".sidebar"))
    page.click('.sb-tab[aria-label="File della directory"]')
    page.wait_for_selector(".sidebar .sb-item.cur")
    check("e l'elenco dei file di origine è a un clic, con la voce aperta evidenziata", "solo-destra.txt" in page.inner_text(".sidebar")
          and page.locator(".sidebar .sb-item.cur").count() == 1)
    check("nessun errore in console (barra, anteprima)", not errors, "; ".join(errors[:3]))
    ctx.close()

    print("== Barra laterale: cartelle dell'anteprima, albero a parte ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    page.keyboard.press("Control+b")
    page.click('.sb-tab[aria-label="File della directory"]')
    page.evaluate("window.__pick = '/t/a'")
    page.locator('.tabpage:not([hidden]) .browse-btn').first.click()
    page.wait_for_function("document.querySelector('.tabpage:not([hidden]) input[aria-label=\"Sinistra\"]').value === '/t/a'")
    page.evaluate("window.__pick = '/t/b'")
    page.locator('.tabpage:not([hidden]) .browse-btn').nth(1).click()
    page.wait_for_selector(".sidebar .sb-item")
    item = lambda title: page.locator(f'.sidebar .sb-item[title="{title}"]')
    check("la cartella è chiusa nella barra e nell'anteprima", item("sub/inner.txt").count() == 0)
    item("sub").click()
    page.wait_for_selector('.sidebar .sb-item[title="sub/inner.txt"]')
    check("aprirla dalla barra non apre la cartella nell'anteprima", page.locator(".dir-preview .dir-body .dir-row", has_text="inner.txt").count() == 0)
    page.locator(".dir-preview .dir-body .dir-row", has_text="sub").first.locator(".twisty").first.click()
    page.wait_for_selector(".dir-preview .dir-body .dir-row:has-text('inner.txt')")
    item("sub").click()
    page.wait_for_timeout(300)
    check("chiuderla dalla barra non chiude quella dell'anteprima", item("sub/inner.txt").count() == 0
          and page.locator(".dir-preview .dir-body .dir-row", has_text="inner.txt").count() >= 1)
    check("nessun errore in console (apertura dalla barra)", not errors, "; ".join(errors[:3]))
    ctx.close()

    print("== Barra laterale: file del confronto di cartelle ==")
    ctx, page, errors = open_page(browser, kind="dirs")
    calls_of = lambda c: page.evaluate("(c) => window.__calls.filter(x => x.cmd === c).map(x => x.args)", c)
    page.fill('input[aria-label="Sinistra"]', "/x/l")
    page.fill('input[aria-label="Destra"]', "/x/r")
    page.click('button[type="submit"]')
    page.wait_for_selector(".dir-body .vl-row", timeout=60_000)
    page.evaluate("window.__fileFixture = 'small.json'")
    page.keyboard.press("Control+b")
    page.click('.sb-tab[aria-label="File della directory"]')
    page.wait_for_selector(".sidebar .sb-item")
    check("nel confronto di cartelle la vista File elenca i file con differenze", "FILE DELLA DIRECTORY" in page.inner_text(".sidebar").upper()
          and page.locator(".sb-item .sb-st.st-different svg").count() > 0, page.inner_text(".sb-title"))
    check("senza file aperto nessuna voce è evidenziata", page.locator(".sb-item.cur").count() == 0)
    n_tabs = page.locator(".doctab").count()
    page.locator('.sb-item[title="d000/f00037.txt"]').click()
    page.wait_for_selector(".viewer", timeout=30_000)
    c = calls_of("compare_files")[-1]
    check("un clic su un file lo apre in un nuovo tab", c["left"] == "/x/l/d000/f00037.txt" and c["right"] == "/x/r/d000/f00037.txt" and page.locator(".doctab").count() == n_tabs + 1, str(c))
    check("nel nuovo tab la barra mostra le differenze del file (non l'elenco dei file)",
          page.evaluate("window.__cfg('state').view") == "diffs")
    page.click('.sb-tab[aria-label="File della directory"]')
    page.wait_for_selector('.sb-item.cur[title="d000/f00037.txt"]')
    check("l'elenco dei file è a un clic, e la voce del file aperto è evidenziata", page.locator(".sb-item.cur").count() == 1)
    check("e si vede la posizione nell'elenco", " di " in page.evaluate("document.querySelector('.sb-title').textContent"), page.inner_text(".sb-title"))
    # expand and collapse at the foot of the list: they act on the list of the sidebar only
    # the identical files have their icon too ("="), grey; with "Solo differenze" they are not in the list
    check("con «Solo differenze» nessun file identico nell'elenco", page.locator(".sidebar .sb-st.st-identical").count() == 0)
    page.click('.sidebar .sb-chip:has-text("Tutti")')
    page.wait_for_function("document.querySelectorAll('.sidebar .sb-st.st-identical svg').length > 0")
    same = page.locator(".sidebar .sb-st.st-identical").first
    check("con «Tutti» i file identici hanno l'icona «=», in grigio, e il nome dello stato nel suggerimento",
          same.locator("svg").count() == 1 and same.get_attribute("title") == "identico" and same.get_attribute("role") == "img"
          and same.evaluate("e => getComputedStyle(e).color") == page.evaluate("getComputedStyle(document.querySelector('.sb-tw')).color"))
    page.locator(".sidebar").screenshot(path=f"{SHOTS}/sidebar_files_all.png")
    check("e le altre icone di stato restano", page.locator(".sidebar .sb-st.st-different svg").count() > 0)
    page.click('.sidebar .sb-chip:has-text("Solo differenze")')
    page.wait_for_function("document.querySelectorAll('.sidebar .sb-st.st-identical').length === 0")
    foot = page.locator(".sidebar .sb-foot")
    gap = page.evaluate("() => { const f = document.querySelector('.sidebar .sb-foot').getBoundingClientRect(), bs = [...document.querySelectorAll('.sidebar .sb-foot button')].map(b => b.getBoundingClientRect()); return Math.round((bs[0].left - f.left) - (f.right - bs[bs.length - 1].right)); }")
    check("i due pulsanti sono al centro della barra (stesso spazio a sinistra e a destra)", abs(gap) <= 2, str(gap))
    page.locator(".doctab-label").nth(1).click()
    page.wait_for_selector(".tabpage:not([hidden]) .dir-body .vl-row")
    main_rows = lambda: page.locator(".tabpage:not([hidden]) .dir-body .vl-row").count()
    main_before = main_rows()
    page.locator(".doctab-label").nth(2).click()
    page.wait_for_selector(".sidebar .sb-item")
    check("in fondo all'elenco ci sono «Espandi» e «Comprimi»", foot.count() == 1 and [x.strip() for x in foot.locator("button").all_inner_texts()] == ["Espandi", "Comprimi"])
    icon_color = lambda sel: page.evaluate("(s) => getComputedStyle(document.querySelector(s)).color", sel)
    check("le icone di «Espandi» e «Comprimi» hanno il colore di quelle della barra delle cartelle (l'azzurro d'accento), non quello del testo",
          icon_color(".sidebar .sb-foot .tb-icon") == icon_color(".dir-tools .tb-icon") != icon_color(".sidebar .sb-foot .sb-btn"),
          f"{icon_color('.sidebar .sb-foot .tb-icon')} / {icon_color('.dir-tools .tb-icon')} / {icon_color('.sidebar .sb-foot .sb-btn')}")
    foot.locator("button", has_text="Comprimi").click()
    page.wait_for_function("!document.querySelector('.sidebar .sb-item[title=\"d000/f00037.txt\"]')")
    check("«Comprimi» chiude tutte le cartelle dell'elenco: restano solo le cartelle, e il pulsante si spegne",
          page.locator('.sidebar .sb-item[title="d000"]').count() == 1 and foot.locator("button", has_text="Comprimi").is_disabled() and foot.locator("button", has_text="Espandi").is_enabled())
    foot.locator("button", has_text="Espandi").click()
    page.wait_for_selector('.sidebar .sb-item[title="d000/f00037.txt"]')
    check("«Espandi» le riapre tutte, e si spegne a sua volta", foot.locator("button", has_text="Espandi").is_disabled() and foot.locator("button", has_text="Comprimi").is_enabled())
    page.locator(".sidebar").screenshot(path=f"{SHOTS}/sidebar_files_foot.png")
    page.locator(".doctab-label").nth(1).click()
    page.wait_for_selector(".tabpage:not([hidden]) .dir-body .vl-row")
    check("il confronto di cartelle nel tab non è cambiato (stesse righe di prima)", main_rows() == main_before, f"{main_rows()} contro {main_before}")
    page.locator(".doctab-label").nth(2).click()
    page.wait_for_selector(".sidebar .sb-item")
    n_tabs = page.locator(".doctab").count()
    page.click('.sidebar .sb-item[title="d000/f00074.txt"]')
    page.wait_for_function("window.__calls.filter(c => c.cmd === 'compare_files').length === 2")
    c = calls_of("compare_files")[-1]
    check("un clic su un altro file dell'elenco lo apre nello stesso tab", c["left"] == "/x/l/d000/f00074.txt" and page.locator(".doctab").count() == n_tabs, str(c))
    page.wait_for_selector('.sb-item.cur[title="d000/f00074.txt"]')
    check("la voce evidenziata segue", True)
    check("aprendo i file dall'elenco la vista resta «File della directory»", page.evaluate("window.__cfg('state').view") == "files")
    check("il tab prende il nome del nuovo file", "f00074.txt" in page.locator(".doctab.active").inner_text())
    page.click('.sidebar .sb-item[title="d000/f00037.txt"]')
    page.wait_for_function("window.__calls.filter(c => c.cmd === 'compare_files').length === 3")
    check("un clic sul primo file torna indietro", calls_of("compare_files")[-1]["left"] == "/x/l/d000/f00037.txt")
    page.wait_for_selector('.sb-item.cur[title="d000/f00037.txt"]')
    # with unsaved changes it asks for confirmation
    page.click('.tabpage:not([hidden]) button[aria-label="Successiva"]'); page.wait_for_timeout(200); settled(page)
    row = page.locator(".pane.right .vrow.chg").first
    row.locator(".num").dblclick(); page.locator("input.line-edit").fill("x"); page.keyboard.press("Enter")
    page.wait_for_function("document.querySelectorAll('.file-meta .dirty').length === 1")
    page.evaluate("window.__confirmAnswer = false")
    page.click('.sidebar .sb-item[title="d000/f00074.txt"]')
    page.wait_for_timeout(500)
    check("con modifiche non salvate e «Annulla» il file non cambia", len(calls_of("compare_files")) == 3)
    check("e i campi dei percorsi non cambiano", page.input_value('.tabpage:not([hidden]) input[aria-label="Sinistra"]').endswith("f00037.txt"),
          page.input_value('.tabpage:not([hidden]) input[aria-label="Sinistra"]'))
    page.evaluate("window.__confirmAnswer = true")
    # the starting tab closed: message
    page.screenshot(path=f"{SHOTS}/34_sidebar_files.png")
    check("nessun errore in console (barra laterale, file)", not errors, "; ".join(errors[:3]))
    ctx.close()

    print("== Barra laterale: vista predefinita per un confronto di file nuovo ==")
    ctx, page, errors = open_page(browser, kind="files")
    page.keyboard.press("Control+b")
    page.click('.sb-tab[aria-label="File della directory"]')
    check("prima: vista File", page.evaluate("window.__cfg('state').view") == "files")
    run_files(page, "small.json")
    page.wait_for_timeout(300)
    check("un confronto di file nuovo porta la barra su «Differenze file»", page.evaluate("window.__cfg('state').view") == "diffs")
    page.click('.sb-tab[aria-label="File della directory"]')
    check("la scelta manuale resta finché non si apre un altro confronto", page.evaluate("window.__cfg('state').view") == "files")
    ctx.close()

    # ------------------------------------------------------------------ the button on the Home
    print("== Il pulsante della barra laterale sulla Home ==")
    ctx, page, errors = open_page(browser, kind=None)
    toggle = page.locator(".sb-toggle")
    check("sulla Home con la barra chiusa il pulsante c'è ma è disabilitato, col motivo nel suggerimento",
          toggle.count() == 1 and toggle.is_disabled() and "apri un confronto" in (toggle.get_attribute("title") or ""),
          str(toggle.get_attribute("title")))
    page.screenshot(path=f"{SHOTS}/sidebar_home_disabled.png", clip={"x": 0, "y": 0, "width": 520, "height": 80})
    page.keyboard.press("Control+b")
    page.wait_for_timeout(150)
    check("Ctrl+B sulla Home con la barra chiusa non la apre", page.locator(".sidebar").count() == 0)
    page.locator(".home button.card").nth(0).click()          # a tab of files: the button works there
    page.wait_for_selector('.tabpage:not([hidden]) .path-field input')
    check("su un tab di confronto il pulsante è attivo", toggle.is_enabled())
    toggle.click()
    page.wait_for_selector(".sidebar")
    page.locator(".doctab-label").first.click()               # back to the Home with the bar open
    page.wait_for_selector(".home")
    check("sulla Home con la barra aperta il pulsante serve a chiuderla",
          toggle.is_enabled() and toggle.get_attribute("aria-pressed") == "true")
    toggle.click()
    page.wait_for_timeout(150)
    check("la barra si chiude e il pulsante torna disabilitato", page.locator(".sidebar").count() == 0 and toggle.is_disabled())
    check("nessun errore in console (pulsante sulla Home)", not errors, "; ".join(errors[:3]))
    ctx.close()
